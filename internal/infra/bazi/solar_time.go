// LocationInfo 城市位置信息
type LocationInfo struct {
	Lon float64
	TZ  float64
}

// LookupCity 查找城市经纬度；找不到返回 error
func LookupCity(name string) (LocationInfo, error) {
	if loc, ok := cityTable[name]; ok {
		return LocationInfo{Lon: loc.Lon, TZ: loc.TZ}, nil
	}
	return LocationInfo{}, fmt.Errorf("未找到城市 %q 的经纬度，请尝试使用标准城市名", name)
}

// ToTrueSolarTime 将标准时间转换为真太阳时
// t: 出生时间（所在时区的标准时间）
// lon: 东经度数（西经为负）
// tzHours: 所在时区 UTC 偏移小时数
func ToTrueSolarTime(t time.Time, lon, tzHours float64) time.Time {
	// 步骤1：LMT 修正（地方平太阳时）
	lmtOffsetMin := (lon - tzHours*15) * 4

	// 步骤2：均时差修正（Equation of Time）
	dayOfYear := float64(t.YearDay())
	B := (360.0 / 365.0) * (dayOfYear - 81) * math.Pi / 180
	eotMin := 9.87*math.Sin(2*B) - 7.53*math.Cos(B) - 1.5*math.Sin(B)

	totalSec := (lmtOffsetMin + eotMin) * 60
	return t.Add(time.Duration(totalSec) * time.Second)
}
